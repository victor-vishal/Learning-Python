#Indexing on strings
#Indexing allows you to access individual characters in a string using their position (index).
#it starts from 0, from left to right and from -1, from right to left
string = "Hello, World!"
print(string[0])  # Output: 'H' (first character)

#negative indexing
#it starts from -1, from right to left
print(string[-1])  # Output: '!' (last character)

