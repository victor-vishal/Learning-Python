#strings creation:
#strings can be created using single quotes(''), double quotes("") or triple quotes(''' '') or (""" """)
string1 = 'Hello, World!'  # using single quotes
string2 = "Hello, World!"  # using double quotes
string3 = '''Hello, World!'''  # using triple single quotes
string4 = """Hello, World!"""  # using triple double quotes

#multiline strings can be created using triple quotes
multiline_string = '''This is a multiline string.
It can span multiple lines.
This is the end of the multiline string.'''

print(multiline_string)
