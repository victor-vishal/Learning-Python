#String Operations
#1. Concatenation
string1 = "Hello"
string2 = "World"
string3 = string1 + " " + string2  # Output: 'Hello World'
print(string3)

#2. Repetition
string4 = "Hi! "
print(string4 * 3)  # Output: 'Hi! Hi! Hi! '

#3. Membership
#Membership operators are used to test if a sequence is presented in an object
# it uses the operators 'in' and 'not in'
String5 = "Hello, World!"
print("Hello" in String5)   # Output: True
print("Python" in String5)  # Output: False

print("x" in String5)  # Output: False

