#Control Flow Statements
#They are used to control the flow of execution of a program based on certain conditions or loops.
#In Python, there are several control flow statements, including:
#1. If statements: Used to execute a block of code if a specified condition is true.
#2. Else statements: Used to execute a block of code if the condition in the if statement is false.
#3. Elif statements: Used to check multiple conditions after an if statement.
#4. For loops: Used to iterate over a sequence (like a list, tuple, or string) and execute a block of code for each item in the sequence.
#5. While loops: Used to execute a block of code as long as a specified condition is true.
#6. Break statement: Used to exit a loop prematurely.
#7. Continue statement: Used to skip the current iteration of a loop and move to the next iteration.
