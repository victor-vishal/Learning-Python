class Student:
    name = "Vishal"
    age = 20

s1 = Student()
# we create an object of class Student
# it is done by calling the class name as a function(a constructor) and then assigning it to a variable

# to access the attributes or properties of the class we use the dot operator
# syntax is object_name.property_name
print(s1.name)
print(s1.age)
